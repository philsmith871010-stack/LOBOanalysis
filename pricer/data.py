def surface_from_rows(header_offsets, rows):
    """rows: [expiry_y, tenor_y, atm_pct, vol_1, vol_2, ...] with header_offsets giving the bp offset of each vol column."""
    out = []
    for r in rows:
        if r[0] in ("", None): continue
        vols = {int(o): float(v) for o, v in zip(header_offsets, r[3:]) if v not in ("", None)}
        out.append((float(r[0]), float(r[1]), float(r[2]), vols))
    return out
